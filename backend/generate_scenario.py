"""Generate random disaster scenarios for ResQ Nexus.

Writes a scenario JSON file in the same format as the demo files in
``data/scenarios/``, so it appears in ``GET /scenarios`` and in the dashboard.

Zones come from one of two sources:

* ``--region NAME``  real localities for a preset region (``data/regions.json``:
  OpenStreetMap names and coordinates, approximate populations)
* ``--center LAT,LON``  synthetic zones scattered within ``--radius-km`` of a point

Damage comes from a simple, explainable hazard model:

* earthquake: point source, intensity = 1 / (1 + (d / D)^2), where D grows with magnitude
* flood: distance d to river lines (preset) or to a random channel, intensity = exp(-d / extent_km)
* wildfire: distance d to the nearest ignition hotspot, intensity = exp(-d / spread_km)

A settlement-type modifier and Gaussian noise are added, then intensity maps to
``damage_severity`` 3 / 2 / 1 / 0 at thresholds 0.70 / 0.45 / 0.20. Road access
falls as intensity rises. Available resources are a fraction ("scarcity") of
the estimated need, so the allocation stage has real trade-offs to make.

Everything generated is SYNTHETIC demo data and is labelled as such.

Examples (run from ``backend/``)::

    python generate_scenario.py --list-regions
    python generate_scenario.py --type earthquake --region kutch --seed 42
    python generate_scenario.py --type wildfire --region kumaon --zones 15 --stdout
    python generate_scenario.py --type flood --center 26.15,85.90 --region-name "Darbhanga, Bihar" --state Bihar
"""
from __future__ import annotations

import argparse
import json
import math
import random
import re
import sys
from pathlib import Path
from typing import Any

from services.scenarios import DISASTER_TYPES, RESOURCE_TYPES, SCENARIO_DIR, Scenario

REGIONS_FILE = Path(__file__).resolve().parent / "data" / "regions.json"

MIN_ZONES, MAX_ZONES = 15, 20
EARTH_RADIUS_KM = 6371.0088

# Intensity (0-1) -> damage_severity (0 none, 1 minor, 2 major, 3 destroyed)
SEVERITY_THRESHOLDS = ((0.70, 3), (0.45, 2), (0.20, 1))

# Settlement kinds: baseline road access and social vulnerability.
BASE_ACCESS = {"city": 0.90, "town": 0.78, "village": 0.58, "remote": 0.30}
BASE_VULNERABILITY = {"city": 0.32, "town": 0.42, "village": 0.58, "remote": 0.70}
# Extra exposure of each settlement kind to a hazard (added to intensity):
# riverine/char hamlets flood first, older village masonry cracks first,
# forest-edge hamlets burn first while towns have firebreaks.
EXPOSURE = {
    "flood": {"city": -0.05, "town": 0.0, "village": 0.05, "remote": 0.15},
    "earthquake": {"city": -0.05, "town": 0.0, "village": 0.05, "remote": 0.05},
    "wildfire": {"city": -0.25, "town": -0.15, "village": 0.0, "remote": 0.10},
}
# How strongly the hazard cuts road access (flooded, cracked or burning roads).
ACCESS_LOSS = {"flood": 0.40, "earthquake": 0.30, "wildfire": 0.20}
ZONE_PREFIX = {"flood": "FL", "earthquake": "EQ", "wildfire": "WF"}

# Share of residents needing relief / displaced, indexed by damage_severity.
AFFECTED_SHARE = (0.0, 0.10, 0.35, 0.75)
DISPLACED_SHARE = (0.0, 0.02, 0.15, 0.50)
# Rounding step for available stock.
RESOURCE_STEP = {"rescue_teams": 1, "medical_kits": 10, "food_packets": 100, "shelters": 1, "vehicles": 1}

DATA_NOTE_REGION = (
    "SYNTHETIC demo data. Zone names and coordinates are real places (OpenStreetMap); "
    "populations are rounded approximations; damage, vulnerability, accessibility and resource "
    "figures are generated by generate_scenario.py and are not real observations."
)
DATA_NOTE_CUSTOM = (
    "SYNTHETIC demo data. Zone locations, names and all figures are randomly generated by "
    "generate_scenario.py and do not describe real places."
)


# --------------------------------------------------------------------------- geometry
def distance_km(a: tuple[float, float], b: tuple[float, float]) -> float:
    """Great-circle (haversine) distance between two (lat, lon) points in km."""
    lat1, lon1, lat2, lon2 = map(math.radians, (a[0], a[1], b[0], b[1]))
    h = math.sin((lat2 - lat1) / 2) ** 2 + math.cos(lat1) * math.cos(lat2) * math.sin((lon2 - lon1) / 2) ** 2
    return 2 * EARTH_RADIUS_KM * math.asin(math.sqrt(h))


def _local_xy(origin: tuple[float, float], p: tuple[float, float]) -> tuple[float, float]:
    """Equirectangular projection (km) around ``origin``; accurate over tens of km."""
    kx = math.radians(1) * EARTH_RADIUS_KM * math.cos(math.radians(origin[0]))
    ky = math.radians(1) * EARTH_RADIUS_KM
    return (p[1] - origin[1]) * kx, (p[0] - origin[0]) * ky


def distance_to_polyline_km(p: tuple[float, float], line: list[list[float]]) -> float:
    """Shortest distance from point ``p`` to a polyline of [lat, lon] vertices."""
    best = math.inf
    for a, b in zip(line, line[1:]):
        ax, ay = _local_xy(p, (a[0], a[1]))
        bx, by = _local_xy(p, (b[0], b[1]))
        dx, dy = bx - ax, by - ay
        seg2 = dx * dx + dy * dy
        t = 0.0 if seg2 == 0 else max(0.0, min(1.0, -(ax * dx + ay * dy) / seg2))
        best = min(best, math.hypot(ax + t * dx, ay + t * dy))
    return best


def bearing_deg(a: tuple[float, float], b: tuple[float, float]) -> float:
    x, y = _local_xy(a, b)
    return math.degrees(math.atan2(x, y)) % 360


def compass(bearing: float) -> str:
    return ("N", "NE", "E", "SE", "S", "SW", "W", "NW")[round(bearing / 45) % 8]


def offset_point(origin: tuple[float, float], dist_km: float, bearing: float) -> tuple[float, float]:
    """Point ``dist_km`` from ``origin`` along ``bearing`` (degrees), small-distance approximation."""
    rad = math.radians(bearing)
    dlat = dist_km * math.cos(rad) / (math.radians(1) * EARTH_RADIUS_KM)
    dlon = dist_km * math.sin(rad) / (math.radians(1) * EARTH_RADIUS_KM * math.cos(math.radians(origin[0])))
    return origin[0] + dlat, origin[1] + dlon


def random_point(centre: tuple[float, float], radius_km: float, rng: random.Random) -> tuple[float, float]:
    """Uniformly random point inside a disc (sqrt keeps the density even)."""
    point = offset_point(centre, radius_km * math.sqrt(rng.random()), rng.uniform(0, 360))
    # Guard against the flat-earth approximation drifting past the radius.
    while distance_km(centre, point) > radius_km:
        point = offset_point(centre, radius_km * math.sqrt(rng.random()), rng.uniform(0, 360))
    return point


def _clamp(x: float, lo: float, hi: float) -> float:
    return max(lo, min(hi, x))


def _latlon(p) -> dict[str, float]:
    return {"latitude": round(p[0], 5), "longitude": round(p[1], 5)}


# --------------------------------------------------------------------------- regions
def load_regions(path: Path = REGIONS_FILE) -> dict[str, dict[str, Any]]:
    """Region presets keyed by id, with places expanded to dicts."""
    raw = json.loads(Path(path).read_text(encoding="utf-8"))
    columns = raw["_place_columns"]
    regions = {}
    for key, region in raw["regions"].items():
        region = dict(region)
        region["places"] = [dict(zip(columns, row)) for row in region["places"]]
        regions[key] = region
    return regions


def _region_extent(places: list[dict[str, Any]]) -> tuple[tuple[float, float], float]:
    centre = (
        sum(p["latitude"] for p in places) / len(places),
        sum(p["longitude"] for p in places) / len(places),
    )
    radius = max(distance_km(centre, (p["latitude"], p["longitude"])) for p in places)
    return centre, radius


# --------------------------------------------------------------------------- hazards
def build_hazard(disaster_type, preset, centre, radius_km, rng, use_preset, magnitude=None):
    """Return (hazard description for the JSON, geometry used to compute intensity)."""
    if use_preset and not preset:
        raise ValueError(f"this region has no preset {disaster_type} hazard")

    if disaster_type == "earthquake":
        if use_preset:
            epicentre, mag = tuple(preset["epicentre"]), float(preset["magnitude"])
        else:
            epicentre, mag = random_point(centre, radius_km * 0.6, rng), round(rng.uniform(6.0, 7.4), 1)
        if magnitude is not None:
            mag = float(magnitude)
        scale = 25.0 * 1.5 ** (mag - 6.8)
        hazard = {"model": "point-source", "epicentre": _latlon(epicentre), "magnitude": mag,
                  "scale_km": round(scale, 1)}
        return hazard, {"points": [epicentre], "kind": "inverse-square", "scale": scale}

    if disaster_type == "flood":
        if preset:
            lines = [line for river in preset["rivers"].values() for line in river]
            extent = float(preset["extent_km"]) if use_preset else round(rng.uniform(6.0, 13.0), 1)
            hazard = {"model": "river-distance", "rivers": list(preset["rivers"]), "extent_km": extent}
        else:
            via = random_point(centre, radius_km * 0.3, rng)
            heading = rng.uniform(0, 180)
            line = [list(offset_point(via, radius_km * 1.5, heading)), list(offset_point(via, radius_km * 1.5, heading + 180))]
            lines = [line]
            extent = round(rng.uniform(5.0, 10.0), 1)
            hazard = {"model": "river-distance", "rivers": ["synthetic river channel"], "extent_km": extent,
                      "channel": [_latlon(p) for p in line]}
        return hazard, {"lines": lines, "kind": "exponential", "scale": extent}

    if disaster_type == "wildfire":
        if use_preset:
            hotspots = [tuple(h) for h in preset["hotspots"]]
            spread = float(preset["spread_km"])
        else:
            hotspots = [random_point(centre, radius_km * 0.8, rng) for _ in range(rng.randint(1, 3))]
            spread = round(rng.uniform(3.5, 6.5), 1)
        hazard = {"model": "hotspots", "hotspots": [_latlon(h) for h in hotspots], "spread_km": spread}
        return hazard, {"points": hotspots, "kind": "exponential", "scale": spread}

    raise ValueError(f"unknown disaster type '{disaster_type}'")


def hazard_intensity(geometry: dict[str, Any], point: tuple[float, float]) -> float:
    """Raw hazard intensity (0-1) at ``point`` before settlement effects and noise."""
    if "lines" in geometry:
        d = min(distance_to_polyline_km(point, line) for line in geometry["lines"])
    else:
        d = min(distance_km(point, p) for p in geometry["points"])
    if geometry["kind"] == "inverse-square":
        return 1.0 / (1.0 + (d / geometry["scale"]) ** 2)
    return math.exp(-d / geometry["scale"])


def severity_from_intensity(x: float) -> int:
    for threshold, severity in SEVERITY_THRESHOLDS:
        if x >= threshold:
            return severity
    return 0


# --------------------------------------------------------------------------- resources
def estimate_need(zones: list[dict[str, Any]]) -> dict[str, int]:
    """Rough relief need implied by the zones' damage and population."""
    affected = sum(z["population"] * AFFECTED_SHARE[z["damage_severity"]] for z in zones)
    displaced = sum(z["population"] * DISPLACED_SHARE[z["damage_severity"]] for z in zones)
    return {
        "rescue_teams": sum((0, 0, 1, 2)[z["damage_severity"]] for z in zones),
        "medical_kits": math.ceil(affected / 25),  # one kit per ~25 affected people
        "food_packets": math.ceil(affected),  # one-day ration per affected person
        "shelters": math.ceil(displaced / 100),  # one unit per ~100 displaced people
        "vehicles": sum((0, 1, 2, 3)[z["damage_severity"]] for z in zones),
    }


def available_resources(need: dict[str, int], scarcity: float) -> dict[str, int]:
    """Available stock = a fraction of the need, rounded down (relief is always short)."""
    stock = {}
    for key in RESOURCE_TYPES:
        step = RESOURCE_STEP[key]
        stock[key] = max(1, math.floor(need[key] * scarcity / step) * step)
    return stock


# --------------------------------------------------------------------------- scenario
def _synthetic_places(centre, radius_km, count, rng) -> list[dict[str, Any]]:
    kinds = rng.choices(["town", "village", "remote"], weights=[0.15, 0.60, 0.25], k=count)
    typical_pop = {"town": 15000, "village": 3000, "remote": 800}
    places: list[dict[str, Any]] = []
    while len(places) < count:
        point = random_point(centre, radius_km, rng)
        if any(distance_km(point, (p["latitude"], p["longitude"])) < 1.5 for p in places):
            continue  # keep zones at least 1.5 km apart
        kind = kinds[len(places)]
        population = int(round(typical_pop[kind] * math.exp(rng.gauss(0, 0.5)), -1))
        d, b = distance_km(centre, point), bearing_deg(centre, point)
        places.append({
            "name": f"Zone {len(places) + 1:02d} ({d:.0f} km {compass(b)})",
            "latitude": point[0], "longitude": point[1], "kind": kind, "population": max(population, 50),
        })
    return places


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "custom"


def _describe(disaster_type, hazard, reference_places) -> tuple[str, str]:
    """Default (title, description) for a scenario."""
    def nearest(point):
        best = min(reference_places, key=lambda p: distance_km(point, (p["latitude"], p["longitude"])))
        d = distance_km(point, (best["latitude"], best["longitude"]))
        where = f"{d:.0f} km {compass(bearing_deg((best['latitude'], best['longitude']), point))} of" if d >= 1 else "at"
        return f"{where} {best['name']}"

    if disaster_type == "earthquake":
        epi = (hazard["epicentre"]["latitude"], hazard["epicentre"]["longitude"])
        return (f"M{hazard['magnitude']:.1f} earthquake",
                f"Hypothetical M{hazard['magnitude']:.1f} earthquake with its epicentre {nearest(epi)}. "
                f"Damage is estimated from distance to the epicentre and settlement type.")
    if disaster_type == "flood":
        synthetic = hazard["rivers"] == ["synthetic river channel"]
        along = "a synthetic river channel" if synthetic else f"the {' and '.join(hazard['rivers'])} rivers"
        title = "River floods" if synthetic else f"{' & '.join(hazard['rivers'])} floods"
        return (title,
                f"Hypothetical monsoon flood along {along}. Inundation is estimated from distance to the "
                f"river channel (decay length {hazard['extent_km']} km) and settlement type.")
    spots = "; ".join(nearest((h["latitude"], h["longitude"])) for h in hazard["hotspots"])
    areas = "ignition area" if len(hazard["hotspots"]) == 1 else f"{len(hazard['hotspots'])} ignition areas"
    return ("Forest fires",
            f"Hypothetical pre-monsoon forest fires from {areas}: {spots}. "
            f"Damage is estimated from distance to the fire front (spread {hazard['spread_km']} km) and settlement type.")


def generate_scenario(
    disaster_type: str,
    *,
    region: str | None = None,
    center: tuple[float, float] | None = None,
    radius_km: float = 30.0,
    zones: int | None = None,
    seed: int | None = None,
    preset_hazard: bool = False,
    magnitude: float | None = None,
    scarcity: float | None = None,
    scenario_id: str | None = None,
    name: str | None = None,
    region_name: str | None = None,
    state: str | None = None,
    noise: float = 0.07,
) -> dict[str, Any]:
    """Build one scenario dict (validated against the Scenario model)."""
    if disaster_type not in DISASTER_TYPES:
        raise ValueError(f"disaster_type must be one of {', '.join(DISASTER_TYPES)}")
    if (region is None) == (center is None):
        raise ValueError("give exactly one of region or center")
    if seed is None:
        seed = random.SystemRandom().randrange(1_000_000)
    rng = random.Random(seed)

    if region is not None:
        regions = load_regions()
        if region not in regions:
            raise ValueError(f"unknown region '{region}' (choose from {', '.join(sorted(regions))})")
        preset_region = regions[region]
        candidates = preset_region["places"]
        count = zones if zones is not None else min(len(candidates), MAX_ZONES)
        if count > len(candidates):
            raise ValueError(f"region '{region}' has only {len(candidates)} places; asked for {count} zones")
        keep = sorted(rng.sample(range(len(candidates)), count))
        places = [candidates[i] for i in keep]
        centre, radius = _region_extent(candidates)
        preset = preset_region.get("hazards", {}).get(disaster_type)
        region_label = region_name or preset_region["name"]
        region_text = preset_region.get("districts", region_label)
        state = state or preset_region["state"]
        data_note = DATA_NOTE_REGION
        reference_places = candidates
        default_id = f"{disaster_type}-{region}-{seed}"
    else:
        assert center is not None  # checked above; narrows the type
        count = zones if zones is not None else rng.randint(MIN_ZONES, MAX_ZONES)
        centre, radius, preset = (float(center[0]), float(center[1])), float(radius_km), None
        places = _synthetic_places(centre, radius, count, rng)
        region_label = region_name or f"{center[0]:.2f}N {center[1]:.2f}E"
        region_text = region_label
        state = state or "Unknown"
        data_note = DATA_NOTE_CUSTOM
        reference_places = places
        default_id = f"{disaster_type}-{_slug(region_label)}-{seed}"

    hazard, geometry = build_hazard(disaster_type, preset, centre, radius, rng, preset_hazard, magnitude)

    zone_list = []
    for index, place in enumerate(places, start=1):
        point = (place["latitude"], place["longitude"])
        kind = place["kind"]
        x = _clamp(hazard_intensity(geometry, point) + EXPOSURE[disaster_type][kind] + rng.gauss(0, noise), 0.0, 1.0)
        access = _clamp(BASE_ACCESS[kind] - ACCESS_LOSS[disaster_type] * x + rng.gauss(0, 0.05), 0.05, 0.98)
        vulnerability = _clamp(BASE_VULNERABILITY[kind] + rng.gauss(0, 0.07), 0.05, 0.95)
        zone_list.append({
            "id": f"{ZONE_PREFIX[disaster_type]}-{index:02d}",
            "name": place["name"],
            "latitude": round(point[0], 5),
            "longitude": round(point[1], 5),
            "disaster_type": disaster_type,
            "damage_severity": severity_from_intensity(x),
            "population": int(place["population"]),
            "vulnerability_index": round(vulnerability, 2),
            "accessibility": round(access, 2),
        })

    if scarcity is None:
        scarcity = 0.6 if preset_hazard else round(rng.uniform(0.45, 0.75), 2)
    resources = available_resources(estimate_need(zone_list), scarcity)

    title, description = _describe(disaster_type, hazard, reference_places)
    scenario = {
        "id": scenario_id or default_id,
        "name": name or f"{title} \u2013 {region_label}",
        "disaster_type": disaster_type,
        "region": region_text,
        "state": state,
        "description": description,
        "synthetic": True,
        "data_note": data_note,
        "hazard": hazard,
        "generator": {"script": "generate_scenario.py", "seed": seed, "preset_hazard": preset_hazard,
                      "scarcity": scarcity},
        "resources": resources,
        "zones": zone_list,
    }
    Scenario.model_validate(scenario)  # fail loudly if the format ever drifts
    return scenario


# --------------------------------------------------------------------------- CLI
def _zone_count(text: str) -> int:
    value = int(text)
    if not MIN_ZONES <= value <= MAX_ZONES:
        raise argparse.ArgumentTypeError(f"zones must be between {MIN_ZONES} and {MAX_ZONES}")
    return value


def _latlon_arg(text: str) -> tuple[float, float]:
    try:
        lat, lon = (float(v) for v in text.split(","))
    except ValueError as exc:
        raise argparse.ArgumentTypeError("use LAT,LON, e.g. 26.15,85.90") from exc
    if not (-90 <= lat <= 90 and -180 <= lon <= 180):
        raise argparse.ArgumentTypeError("latitude/longitude out of range")
    return lat, lon


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Generate a random ResQ Nexus disaster scenario (synthetic demo data).",
        epilog="Example: python generate_scenario.py --type earthquake --region kutch --seed 42",
    )
    parser.add_argument("--type", choices=DISASTER_TYPES, help="disaster type (default: the region's usual hazard)")
    where = parser.add_mutually_exclusive_group()
    where.add_argument("--region", help="preset region id with real localities (see --list-regions)")
    where.add_argument("--center", type=_latlon_arg, metavar="LAT,LON",
                       help="centre for synthetic zones (no coastline awareness: prefer inland points)")
    parser.add_argument("--radius-km", type=float, default=30.0, help="radius for --center (default 30)")
    parser.add_argument("--region-name", help="display name for the region, e.g. 'Darbhanga, Bihar'")
    parser.add_argument("--state", help="Indian state (default: from the region preset)")
    parser.add_argument("--zones", type=_zone_count, help=f"number of zones, {MIN_ZONES}-{MAX_ZONES}")
    parser.add_argument("--seed", type=int, help="random seed for a reproducible scenario")
    parser.add_argument("--preset-hazard", action="store_true",
                        help="use the region's reference hazard instead of a random one")
    parser.add_argument("--magnitude", type=float, help="earthquake magnitude override")
    parser.add_argument("--scarcity", type=float,
                        help="available resources as a fraction of estimated need (default: random 0.45-0.75)")
    parser.add_argument("--id", dest="scenario_id", help="scenario id (default: <type>-<region>-<seed>)")
    parser.add_argument("--name", help="scenario display name")
    out = parser.add_mutually_exclusive_group()
    out.add_argument("--out", type=Path, help="output file (default: data/scenarios/<id>.json)")
    out.add_argument("--stdout", action="store_true", help="print the JSON instead of writing a file")
    parser.add_argument("--force", action="store_true", help="overwrite an existing file")
    parser.add_argument("--list-regions", action="store_true", help="list preset regions and exit")
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)

    if args.list_regions:
        for key, region in sorted(load_regions().items()):
            hazards = ", ".join(sorted(region.get("hazards", {}))) or "none"
            print(f"{key:15} {region['name']} - {len(region['places'])} places; preset hazards: {hazards}")
        return 0

    if args.region is None and args.center is None:
        parser.error("give --region or --center (see --list-regions)")
    disaster_type: str | None = args.type
    if disaster_type is None:
        if args.region is None:
            parser.error("--type is required with --center")
        regions = load_regions()
        if args.region not in regions:
            parser.error(f"unknown region '{args.region}' (see --list-regions)")
        disaster_type = str(regions[args.region]["default_disaster"])
    scenario_id = args.scenario_id or (args.out.stem if args.out else None)

    try:
        scenario = generate_scenario(
            disaster_type, region=args.region, center=args.center, radius_km=args.radius_km,
            zones=args.zones, seed=args.seed, preset_hazard=args.preset_hazard, magnitude=args.magnitude,
            scarcity=args.scarcity, scenario_id=scenario_id, name=args.name,
            region_name=args.region_name, state=args.state,
        )
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    text = json.dumps(scenario, indent=2, ensure_ascii=False) + "\n"
    if args.stdout:
        sys.stdout.buffer.write(text.encode("utf-8"))
        return 0

    path = args.out or SCENARIO_DIR / f"{scenario['id']}.json"
    if path.exists() and not args.force:
        print(f"error: {path} exists (use --force to overwrite)", file=sys.stderr)
        return 1
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")

    counts = [sum(z["damage_severity"] == s for z in scenario["zones"]) for s in (3, 2, 1, 0)]
    print(f"Wrote {path}")
    print(f"  id={scenario['id']} type={disaster_type} seed={scenario['generator']['seed']} "
          f"zones={len(scenario['zones'])} (destroyed {counts[0]}, major {counts[1]}, "
          f"minor {counts[2]}, none {counts[3]})")
    print("  resources: " + ", ".join(f"{k}={v}" for k, v in scenario["resources"].items()))
    return 0


